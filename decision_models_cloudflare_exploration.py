"""## Run it and keep the evidence
Only the next cell sends requests. Provider order alternates per message; there are no automatic retries or silent model substitutions. A provider HTTP failure pauses that provider. Malformed decision outputs are retained as failed decisions, not repaired behind the scenes.

Each run gets a new output directory. Requests, responses, model IDs when supplied, UTC timestamps, and end-to-end timings are saved. Credentials, account IDs and headers are excluded.
"""

class ExperimentError(Exception):
    pass


def probability(value):
    if isinstance(value, bool) or not isinstance(value,(float,int)) or not math.isfinite(value) or not 0 <= value <= 1:
        raise ExperimentError("Invalid probability value")
    return float(value)


def parse_result(name, body):
    if not isinstance(body,dict):
        raise ExperimentError("Expected a JSON object from provider")
    if body.get("success") is False:
        raise ExperimentError("Cloudflare returned success=false")
    result = body.get("result",body)
    if not isinstance(result,dict):
        raise ExperimentError("Missing result object")
    if name == "Clef":
        answers = result.get("answers",{})
        distributions = {}
        values = {}
        for field,options in (("team",TEAMS),("next_step",ACTIONS)):
            answer = answers.get(field,{})
            choice = answer.get("choice")
            probs = answer.get("probabilities")
            if choice not in options or not isinstance(probs,dict) or set(probs)!=set(options):
                raise ExperimentError("Unexpected Clef choice schema")
            probs = {k:probability(v) for k,v in probs.items()}
            if abs(sum(probs.values())-1)>0.03:
                raise ExperimentError("Clef probabilities do not approximately sum to one")
            values[field]=choice
            distributions[field]=probs
        p_urgent=probability(answers.get("urgent",{}).get("noul"))
        values["urgent"]=p_urgent>=0.5
        return values, {"probabilities":distributions,"urgent_probability":p_urgent}
    # Cloudflare native responses may expose response directly or OpenAI-style choices.
    generated = result.get("response")
    if generated is None:
        choices = result.get("choices",[])
        if choices and isinstance(choices[0],dict):
            if choices[0].get("finish_reason")=="length":
                raise ExperimentError("LLM generation hit max_tokens; inspect response and raise cap explicitly")
            generated = choices[0].get("message",{}).get("content")
    if isinstance(generated,str):
        try:
            values=json.loads(generated)
        except json.JSONDecodeError:
            raise ExperimentError("LLM response was not valid JSON; no repair applied") from None
    else:
        values=generated
    if not isinstance(values,dict) or set(values)!={"team","next_step","urgent"}:
        raise ExperimentError("LLM result does not match the requested fields")
    if values["team"] not in TEAMS or values["next_step"] not in ACTIONS or not isinstance(values["urgent"],bool):
        raise ExperimentError("LLM result contains invalid decision values")
    return values, {}


def clean_for_export(value):
    # Redact known credentials even if a provider were to echo one unexpectedly.
    text=json.dumps(value)
    for config in providers.values():
        text=text.replace(config["key"],"[redacted]")
    if "account" in globals() and account:
        text=text.replace(account,"[redacted-account]")
    return json.loads(text)


def run_experiment():
    if not providers:
        raise ExperimentError("Add at least one provider key in setup first")
    planned=len(CASES)*len(providers)
    if planned>MAX_CALLS:
        raise ExperimentError("Planned calls exceed MAX_CALLS; adjust before running")
    run_id=datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    out=Path("clef_exploration")/run_id
    out.mkdir(parents=True,exist_ok=True)
    rows,paused=[],set()
    for i,case in enumerate(CASES):
        names=list(providers)
        if i%2:names.reverse()
        for name in names:
            if name in paused:continue
            config=providers[name]
            payload=make_payload(name,case["message"])
            row={"provider":name,"requested_model":config["model"],"case_id":case["id"],
                 "message":case["message"],"expected":case["expected"],"request_body":payload,
                 "timestamp_utc":datetime.now(timezone.utc).isoformat()}
            start=time.perf_counter()
            try:
                request=urllib.request.Request(config["url"],data=json.dumps(payload).encode(),
                    headers={"Authorization":"Bearer "+config["key"],"Content-Type":"application/json"})
                with urllib.request.build_opener(NoRedirect()).open(request,timeout=TIMEOUT_SECONDS) as response:
                    raw=response.read()
                    row["round_trip_ms"]=(time.perf_counter()-start)*1000
                    row["http_status"]=response.status
                try:body=json.loads(raw)
                except (ValueError,UnicodeDecodeError):
                    raise ExperimentError("Provider returned non-JSON data") from None
                row["raw_response"]=body
                result=body.get("result",body) if isinstance(body,dict) else {}
                if isinstance(result,dict):
                    row["returned_model"]=result.get("model")
                    row["usage"]=result.get("usage")
                values,extra=parse_result(name,body)
                row.update(status="ok",values=values,**extra)
                row["matches_policy"]=all(values[k]==v for k,v in case["expected"].items())
                print(f"{name:3} | {case['id']:20} | {values} | {row['round_trip_ms']:.0f} ms")
            except urllib.error.HTTPError as exc:
                row.update(status="error",http_status=exc.code,error=f"HTTP {exc.code}; check provider access, balance, limits, and request schema")
                paused.add(name)
                print(name,row["error"],"— provider paused")
            except urllib.error.URLError:
                row.update(status="error",error="Network request failed; provider paused")
                paused.add(name)
                print(name,row["error"])
            except ExperimentError as exc:
                row.update(status="error",error=str(exc))
                print(name,row["error"])
            except Exception as exc:
                row.update(status="error",error=type(exc).__name__)
                paused.add(name)
                print(name,"Unexpected transport/response failure; provider paused")
            row.setdefault("round_trip_ms",(time.perf_counter()-start)*1000)
            rows.append(clean_for_export(row))
            (out/"results.json").write_text(json.dumps(rows,indent=2),encoding="utf-8")
    return rows,out

class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self,*args,**kwargs):
        return None

records, OUT = run_experiment()

